static const uint8_t kRcon[11] = {0x00,0x01,0x02,0x04,0x08,0x10,0x20,0x40,0x80,0x1B,0x36};

static inline uint8_t xtime(uint8_t x) {
    return (uint8_t)((x << 1) ^ (((x >> 7) & 1) * 0x1b));
}
static inline uint8_t gmul(uint8_t a, uint8_t b) {
    return (uint8_t)(
        ((b & 1) ? a : 0) ^
        ((b & 2) ? xtime(a) : 0) ^
        ((b & 4) ? xtime(xtime(a)) : 0) ^
        ((b & 8) ? xtime(xtime(xtime(a))) : 0) ^
        ((b & 16)? xtime(xtime(xtime(xtime(a)))) : 0)
    );
}
static inline uint32_t rot_word(uint32_t w) {
    return (w << 8) | (w >> 24);
}
static inline uint32_t sub_word(uint32_t w) {
    return (uint32_t(kSbox[(w >> 24) & 0xFF]) << 24) |
           (uint32_t(kSbox[(w >> 16) & 0xFF]) << 16) |
           (uint32_t(kSbox[(w >>  8) & 0xFF]) <<  8) |
            uint32_t(kSbox[(w      ) & 0xFF]);
}

static void aes128_key_expansion(const uint8_t key[16], uint32_t rk[44]) {
    for (int i = 0; i < 4; ++i) {
        rk[i] = (uint32_t(key[i*4]) << 24) | (uint32_t(key[i*4+1]) << 16) |
                (uint32_t(key[i*4+2]) << 8) | uint32_t(key[i*4+3]);
    }
    for (int i = 4; i < 44; ++i) {
        uint32_t t = rk[i-1];
        if (i % 4 == 0) {
            t = sub_word(rot_word(t)) ^ (uint32_t(kRcon[i/4]) << 24);
        }
        rk[i] = rk[i-4] ^ t;
    }
}

void AesCbc::aes128_encrypt_block(const uint32_t rk[44], const uint8_t in[16], uint8_t out[16]) {
    uint8_t s[16];
    std::memcpy(s, in, 16);
    // AddRoundKey round 0
    for (int i = 0; i < 16; ++i) s[i] ^= (uint8_t)(rk[i/4] >> (24 - (i%4)*8));
    for (int r = 1; r < 10; ++r) {
        for (int i = 0; i < 16; ++i) s[i] = kSbox[s[i]];
        // ShiftRows
        uint8_t t;
        t = s[1]; s[1] = s[5]; s[5] = s[9];  s[9]  = s[13]; s[13] = t;
        t = s[2]; s[2] = s[10]; s[10] = t;
        uint8_t t2 = s[3]; s[3] = s[15]; s[15] = s[11]; s[11] = s[7]; s[7] = t2;
        // MixColumns
        for (int c = 0; c < 4; ++c) {
            uint8_t a0 = s[c*4], a1 = s[c*4+1], a2 = s[c*4+2], a3 = s[c*4+3];
            uint8_t h = (uint8_t)((a0 >> 7) & 1);
            s[c*4  ] = (uint8_t)((a0 << 1) ^ a1 ^ ((a1 >> 7) & 1) ^ h);
            uint8_t h1 = (uint8_t)((a1 >> 7) & 1);
            s[c*4+1] = (uint8_t)((a1 << 1) ^ a2 ^ ((a2 >> 7) & 1) ^ h1);
            uint8_t h2 = (uint8_t)((a2 >> 7) & 1);
            s[c*4+2] = (uint8_t)((a2 << 1) ^ a3 ^ ((a3 >> 7) & 1) ^ h2);
            uint8_t h3 = (uint8_t)((a3 >> 7) & 1);
            s[c*4+3] = (uint8_t)((a3 << 1) ^ a0 ^ h ^ h3);
        }
        // AddRoundKey
        for (int i = 0; i < 16; ++i) s[i] ^= (uint8_t)(rk[r*4 + i/4] >> (24 - (i%4)*8));
    }
    // Final round (no MixColumns)
    for (int i = 0; i < 16; ++i) s[i] = kSbox[s[i]];
    uint8_t t;
    t = s[1]; s[1] = s[5]; s[5] = s[9];  s[9]  = s[13]; s[13] = t;
    t = s[2]; s[2] = s[10]; s[10] = t;
    uint8_t t2 = s[3]; s[3] = s[15]; s[15] = s[11]; s[11] = s[7]; s[7] = t2;
    for (int i = 0; i < 16; ++i) s[i] ^= (uint8_t)(rk[40 + i/4] >> (24 - (i%4)*8));
    std::memcpy(out, s, 16);
}

void AesCbc::aes128_decrypt_block(const uint32_t rk[44], const uint8_t in[16], uint8_t out[16]) {
    uint8_t s[16];
    std::memcpy(s, in, 16);
    // Inv AddRoundKey + Inv ShiftRows + Inv SubBytes (final round reversed)
    for (int i = 0; i < 16; ++i) s[i] ^= (uint8_t)(rk[40 + i/4] >> (24 - (i%4)*8));
    // Inv ShiftRows
    uint8_t t;
    t = s[13]; s[13] = s[9]; s[9] = s[5]; s[5] = s[1]; s[1] = t;
    t = s[2]; s[2] = s[10]; s[10] = t;
    uint8_t t2 = s[7]; s[7] = s[11]; s[11] = s[15]; s[15] = s[3]; s[3] = t2;
    for (int i = 0; i < 16; ++i) s[i] = kInvSbox[s[i]];
    for (int r = 9; r >= 1; --r) {
        for (int i = 0; i < 16; ++i) s[i] ^= (uint8_t)(rk[r*4 + i/4] >> (24 - (i%4)*8));
        // Inv MixColumns (×0e 0b 0d 09)
        for (int c = 0; c < 4; ++c) {
            uint8_t a0 = s[c*4], a1 = s[c*4+1], a2 = s[c*4+2], a3 = s[c*4+3];
            s[c*4  ] = (uint8_t)(gmul(a0,0x0e) ^ gmul(a1,0x0b) ^ gmul(a2,0x0d) ^ gmul(a3,0x09));
            s[c*4+1] = (uint8_t)(gmul(a0,0x09) ^ gmul(a1,0x0e) ^ gmul(a2,0x0b) ^ gmul(a3,0x0d));
            s[c*4+2] = (uint8_t)(gmul(a0,0x0d) ^ gmul(a1,0x09) ^ gmul(a2,0x0e) ^ gmul(a3,0x0b));
            s[c*4+3] = (uint8_t)(gmul(a0,0x0b) ^ gmul(a1,0x0d) ^ gmul(a2,0x09) ^ gmul(a3,0x0e));
        }
        // Inv ShiftRows
        t = s[13]; s[13] = s[9]; s[9] = s[5]; s[5] = s[1]; s[1] = t;
        t = s[2]; s[2] = s[10]; s[10] = t;
        t2 = s[7]; s[7] = s[11]; s[11] = s[15]; s[15] = s[3]; s[3] = t2;
        // Inv SubBytes
        for (int i = 0; i < 16; ++i) s[i] = kInvSbox[s[i]];
    }
    for (int i = 0; i < 16; ++i) s[i] ^= (uint8_t)(rk[i/4] >> (24 - (i%4)*8));
    std::memcpy(out, s, 16);
}

/* ---------- AesCbc 公共 API ---------- */
AesCbc::AesCbc()  { std::memset(round_keys_, 0, sizeof(round_keys_)); ready_ = false; }
AesCbc::~AesCbc() = default;

bool AesCbc::set_key(const uint8_t key[16]) {
    if (!key) return false;
    aes128_key_expansion(key, round_keys_);
    ready_ = true;
    return true;
}

bool AesCbc::encrypt(const uint8_t iv[16], const uint8_t* in, size_t in_len,
                     uint8_t* out, size_t* out_len) {
    if (!ready_ || !in || !out || !out_len || !iv) return false;
    // PKCS#7 padding size
    size_t pad = 16 - (in_len % 16);
    size_t needed = in_len + pad;
    if (*out_len < needed) { *out_len = needed; return false; }
    // 把明文 + 填充分批拷贝到一个连续缓冲，避免反复 XOR 错
    std::vector<uint8_t> tmp(in, in + in_len);
    for (size_t i = 0; i < pad; ++i) tmp.push_back((uint8_t)pad);
    // CBC 链式加密
    uint8_t prev[16];
    std::memcpy(prev, iv, 16);
    size_t nblocks = tmp.size() / 16;
    uint8_t block[16];
    for (size_t b = 0; b < nblocks; ++b) {
        for (int i = 0; i < 16; ++i) block[i] = tmp[b*16 + i] ^ prev[i];
        aes128_encrypt_block(round_keys_, block, &out[b*16]);
        std::memcpy(prev, &out[b*16], 16);
    }
    *out_len = nblocks * 16;
    return true;
}

bool AesCbc::decrypt(const uint8_t iv[16], const uint8_t* in, size_t in_len,
                     uint8_t* out, size_t* out_len) {
    if (!ready_ || !in || !out || !out_len || !iv) return false;
    if (in_len % 16 != 0) return false;
    size_t nblocks = in_len / 16;
    if (nblocks == 0) return false;
    if (*out_len < in_len) { *out_len = in_len; return false; }
    uint8_t prev[16];
    std::memcpy(prev, iv, 16);
    for (size_t b = 0; b < nblocks; ++b) {
        uint8_t dec[16];
        aes128_decrypt_block(round_keys_, &in[b*16], dec);
        for (int i = 0; i < 16; ++i) out[b*16 + i] = dec[i] ^ prev[i];
        std::memcpy(prev, &in[b*16], 16);
    }
    // PKCS#7 校验：最后一个字节就是 pad 长度（1~16）
    uint8_t pad = out[in_len - 1];
    if (pad < 1 || pad > 16) return false;
    for (size_t i = 0; i < pad; ++i) {
        if (out[in_len - 1 - i] != pad) return false;
    }
    *out_len = in_len - pad;
    return true;
}

std::vector<uint8_t> AesCbc::encrypt_vec(const uint8_t iv[16], const uint8_t* in, size_t len) {
    size_t pad = 16 - (len % 16);
    size_t cap = len + pad;
    std::vector<uint8_t> out(cap);
    size_t out_len = cap;
    if (!encrypt(iv, in, len, out.data(), &out_len)) return {};
    out.resize(out_len);
    return out;
}
std::vector<uint8_t> AesCbc::decrypt_vec(const uint8_t iv[16], const uint8_t* in, size_t len) {
    if (len == 0 || len % 16 != 0) return {};
    std::vector<uint8_t> out(len);
    size_t out_len = len;
    if (!decrypt(iv, in, len, out.data(), &out_len)) return {};
    out.resize(out_len);
    return out;
}

